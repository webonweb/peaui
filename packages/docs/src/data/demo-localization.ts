export function localizeDemoData<T>(value: T): T {
  if (locale.value === 'pl') return value;
  if (typeof value === 'string') return (english[value] ?? value) as T;
  if (Array.isArray(value)) return value.map((entry) => localizeDemoData(entry)) as T;
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, entry]) => [english[key] ?? key, localizeDemoData(entry)]),
    ) as T;
  }
  return value;
}
