import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const componentsRoot = join(root, 'src/components');
function scan(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return scan(path);
    return entry.name === 'index.tsx'
      ? [relative(componentsRoot, dirname(path)).replaceAll('\\', '/')]
      : [];
  });
}
const entries = scan(componentsRoot).sort();
const header = '// Generated by scripts/generate-package-entries.mjs.\n';
const files = {
  'src/component-imports.ts':
    header +
    `export const componentImports: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries.map((path) => [path.split('/').at(-1), path])), null, 2)};\n`,
  'src/react.ts':
    header +
    entries
      .map(
        (path) =>
          `export { default as ${path.split('/').at(-1)} } from './components/${path}/index';\nexport type * from './components/${path}/index';`,
      )
      .join('\n') +
    '\n',
};
for (const [relativePath, source] of Object.entries(files)) {
  const path = join(root, relativePath);
  const output = await format(source, { ...(await resolveConfig(path)), filepath: path });
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== output)
      throw new Error(`Regenerate package entries: ${relativePath}`);
  } else writeFileSync(path, output);
}
console.log(`Package entries: ${entries.length} components.`);
